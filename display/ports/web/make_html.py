"""make_html.py -- pack the web display into one self-contained page.

    python3 make_html.py <module.js> <width> <height> <out.html> <out.ts>

Inlines the Emscripten module (built with SINGLE_FILE, so the WebAssembly
is inside it) and shell.js into shell.html. The page loads with no server
and no network. Also writes the page as a TypeScript string constant for
the companion app, which hands it to a WebView or an iframe.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def main(module_path, width, height, out_html, out_ts):
    shell_html = open(os.path.join(HERE, "shell.html"), encoding="utf-8").read()
    shell_js = open(os.path.join(HERE, "shell.js"), encoding="utf-8").read()
    module_js = open(module_path, encoding="utf-8").read()
    shell_js = shell_js.replace("NOAIDI_WIDTH", str(int(width))).replace("NOAIDI_HEIGHT", str(int(height)))
    for text in (module_js, shell_js):
        if "</script" in text:
            sys.exit("make_html: a script contains </script")
    page = shell_html.replace("/*MODULE*/", module_js).replace("/*SHELL*/", shell_js)
    with open(out_html, "w", encoding="utf-8") as f:
        f.write(page)
    with open(out_ts, "w", encoding="utf-8") as f:
        f.write("// GENERATED by display/ports/web/make_html.py; do not edit: run make -C display web.\n")
        f.write("//\n// Copyright © 2026 Thor H. Linløkken <thj@thj.no>\n// License: CERN-OHL-S v2\n//\n")
        f.write("// The Noaidi display (LVGL compiled to WebAssembly) as one self-contained page.\n\n")
        f.write(f"export const DISPLAY_WIDTH = {int(width)};\n")
        f.write(f"export const DISPLAY_HEIGHT = {int(height)};\n")
        f.write(f"export const DISPLAY_HTML = {json.dumps(page, ensure_ascii=False)};\n")


if __name__ == "__main__":
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    main(*sys.argv[1:])
