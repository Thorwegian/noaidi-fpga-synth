"""gen_factory.py -- the synth's factory content as a TypeScript module.

    python3 tools/gen_factory/gen_factory.py ../app/storage ../app/main/storage.c \
        > src/generated/factoryPresets.ts

FACTORY_FILES: every .toml under app/storage (the factory presets,
banks.toml, system.toml) as text, so the app opens with a representative
sound and lists the factory library without file access.

PRESET_CATEGORIES: the category folders every Presets/User has, read from
the firmware's own list (s_categories in app/main/storage.c).
"""
import json
import os
import re
import sys


def categories(storage_c):
    text = open(storage_c, encoding="utf-8").read()
    m = re.search(r"s_categories\[\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("gen_factory: no s_categories in " + storage_c)
    return re.findall(r'"([^"]+)"', m.group(1))


def main(storage, storage_c):
    files = {}
    for root, _, names in os.walk(storage):
        for name in names:
            if name.endswith(".toml"):
                path = os.path.join(root, name)
                files[os.path.relpath(path, storage).replace(os.sep, "/")] = open(path, encoding="utf-8").read()
    print("// GENERATED by companion/tools/gen_factory from app/storage and")
    print("// app/main/storage.c; do not edit: run make -C companion manifest.")
    print("//\n// Copyright © 2026 Thor H. Linløkken <thj@thj.no>\n// License: CERN-OHL-S v2\n")
    print("// The category folders every Presets/User has (the firmware's s_categories).")
    print(f"export const PRESET_CATEGORIES: readonly string[] = {json.dumps(categories(storage_c))};\n")
    print("// Path below the synth's /storage → file text.")
    print("export const FACTORY_FILES: Readonly<Record<string, string>> = {")
    for path in sorted(files):
        print(f"  {json.dumps(path)}: {json.dumps(files[path], ensure_ascii=False)},")
    print("};")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
