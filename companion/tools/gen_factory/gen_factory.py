"""gen_factory.py -- the factory patches and system.toml, as a TypeScript module.

    python3 tools/gen_factory/gen_factory.py ../app/storage > src/generated/factoryPresets.ts

The app bundles the firmware's factory content (app/storage) as text, so it
opens with a representative sound and needs no file access to do so.
"""
import json
import os
import sys


def main(storage):
    files = {}
    for root, _, names in os.walk(storage):
        for name in names:
            if name.endswith(".toml"):
                path = os.path.join(root, name)
                files[os.path.relpath(path, storage).replace(os.sep, "/")] = open(path, encoding="utf-8").read()
    print("// GENERATED by companion/tools/gen_factory from app/storage; do not edit:")
    print("// run make -C companion manifest.")
    print("//\n// Copyright © 2026 Thor H. Linløkken <thj@thj.no>\n// License: CERN-OHL-S v2\n")
    print("// Path below the synth's /storage → file text.")
    print("export const FACTORY_FILES: Readonly<Record<string, string>> = {")
    for path in sorted(files):
        print(f"  {json.dumps(path)}: {json.dumps(files[path], ensure_ascii=False)},")
    print("};")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
