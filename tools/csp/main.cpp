namespace {

int usage() {
    std::fputs(
            "usage: csp asm program.s...\n"
            "       csp header program.s...\n"
            "       csp sim program.s... [-n passes] [-w name]... [-s name=value@pass]...\n"
            "       (several program files are joined into one, in order)\n",
            stderr);
    return 2;
}

bool read_file(const std::string &path, std::string &text) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
        return false;
    }
    std::ostringstream contents;
    contents << in.rdbuf();
    text = contents.str();
    return true;
}

// The files a program was joined from, to say which one a line is in.
struct Sources {
    struct Part {
        std::string path;
        int first_line; // of the joined text, from 1
    };
    std::vector<Part> parts;
    std::string text;

    std::string where(int line) const {
        const Part *part = &parts.front();
        for (const Part &candidate : parts) {
            if (candidate.first_line <= line) {
                part = &candidate;
            }
        }
        return part->path + ":" + std::to_string(line - part->first_line + 1);
    }
};

bool report(const Sources &sources, const csp::Program &program) {
    for (const csp::Diagnostic &d : program.diagnostics) {
        std::fprintf(stderr, "%s: %s: %s\n", sources.where(d.line).c_str(),
                     d.error ? "error" : "warning", d.message.c_str());
    }
    return program.ok();
}

int assemble_command(const csp::Program &program) {
    for (size_t at = 0; at < program.words.size(); ++at) {
        std::printf("%04zx  %09llx  ; line %d\n", at,
                    static_cast<unsigned long long>(program.words[at]),
                    program.source_lines[at]);
    }
    for (const csp::ConstantWrite &constant : program.constants) {
        std::printf("const 0x%03x = %d  (%.6f)\n", constant.address,
                    constant.raw,
                    static_cast<double>(constant.raw) / csp::word_one);
    }
    return 0;
}

// A symbol as a C++ constant name: NAME_LIKE_THIS → name_like_this.
std::string constant_name(const std::string &symbol) {
    std::string name = symbol;
    std::transform(name.begin(), name.end(), name.begin(), [](unsigned char c) {
        return static_cast<char>(std::tolower(c));
    });
    return name;
}

// The header the firmware builds the control program from. The format is
// the repository's (Java Code Conventions): `make format` leaves it be.
int header_command(const csp::Program &program,
                   const std::vector<std::string> &files) {
    std::printf(
            "// control_program.hpp — the CSP's control program, as machine "
            "code\n"
            "//\n"
            "// Copyright © 2026 Thor H. Linløkken <thj@thj.no>\n"
            "// License: CERN-OHL-S v2\n"
            "//\n"
            "// Generated by `csp header` (make csp-header) from, in this "
            "order:\n");
    for (const std::string &file : files) {
        std::printf("//   %s\n", file.c_str());
    }
    std::printf(
            "// Do not edit: make csp-test checks that it is current.\n"
            "// The names are those of tools/csp/programs/map.s, in lower "
            "case;\n// the labels of the code are left out.\n\n"
            "#pragma once\n\n"
            "#include <array>\n"
            "#include <cstdint>\n\n"
            "namespace csp::control {\n\n");
    std::printf("// The instructions, 36 bits each.\n"
                "inline constexpr std::array<uint64_t, %zu> words{\n",
                program.words.size());
    for (size_t at = 0; at < program.words.size(); at += 4) {
        std::printf("   ");
        for (size_t k = at; k < std::min(at + 4, program.words.size()); ++k) {
            std::printf(" 0x%09llxull,",
                        static_cast<unsigned long long>(program.words[k]));
        }
        std::printf("\n");
    }
    std::printf("};\n\n"
                "// The constant registers the firmware writes once.\n"
                "struct Constant {\n"
                "    int address;\n"
                "    int32_t raw;\n"
                "};\n\n"
                "inline constexpr std::array<Constant, %zu> constants{\n",
                program.constants.size());
    for (const csp::ConstantWrite &constant : program.constants) {
        std::printf("    Constant{0x%03x, %d},\n", constant.address,
                    constant.raw);
    }
    // Registers, blocks and fields are in capitals; the labels of the code
    // (voices:, done:) are not constants anybody needs.
    std::printf("};\n\n// Registers, blocks and fields.\n");
    for (const auto &[name, value] : program.symbols) {
        const bool label = std::any_of(name.begin(), name.end(),
                                       [](unsigned char c) {
                                           return std::islower(c);
                                       });
        if (!label) {
            std::printf("inline constexpr int %s = %d;\n",
                        constant_name(name).c_str(), value);
        }
    }
    std::printf("\n} // namespace csp::control\n");
    return 0;
}

struct ScriptedWrite {
    int address;
    int32_t raw;
    int before_pass;
};

int simulate_command(const csp::Program &program, int passes,
                     const std::vector<std::string> &watch,
                     const std::vector<ScriptedWrite> &writes) {
    csp::Processor processor;
    for (const csp::ConstantWrite &constant : program.constants) {
        processor.write(constant.address, constant.raw);
    }
    processor.swap();
    processor.pass(); // held: applies the constants
    processor.load(program.words);
    processor.release();

    int status = 0;
    for (int pass = 1; pass <= passes; ++pass) {
        bool queued = false;
        for (const ScriptedWrite &write : writes) {
            if (write.before_pass == pass) {
                processor.write(write.address, write.raw);
                queued = true;
            }
        }
        if (queued) {
            processor.swap();
        }
        const csp::PassReport report = processor.pass();
        std::printf("pass %d: %d cycles", pass, report.cycles);
        for (const std::string &name : watch) {
            const int address = program.symbols.at(name);
            std::printf("  %s=%d", name.c_str(), processor.read(address));
        }
        std::printf("\n");
        for (const std::string &error : report.errors) {
            std::printf("  error: %s\n", error.c_str());
            status = 1;
        }
        for (int stale : report.stale_sinks) {
            std::printf("  error: sink 0x%03x not written this pass\n",
                        csp::sink_base + stale);
            status = 1;
        }
    }
    return status;
}

} // namespace

int main(int argc, char **argv) {
    if (argc < 3) {
        return usage();
    }
    const std::string command = argv[1];
    // the program: every leading argument that is a file, joined
    Sources sources;
    int arg = 2;
    for (; arg < argc && argv[arg][0] != '-'; ++arg) {
        std::string text;
        if (!read_file(argv[arg], text)) {
            std::fprintf(stderr, "cannot read %s\n", argv[arg]);
            return 2;
        }
        const int first_line =
                1
                + static_cast<int>(std::count(sources.text.begin(),
                                              sources.text.end(), '\n'));
        sources.parts.push_back({argv[arg], first_line});
        sources.text += text;
        if (!text.empty() && text.back() != '\n') {
            sources.text += '\n';
        }
    }
    if (sources.parts.empty()) {
        return usage();
    }
    const csp::Program program = csp::assemble(sources.text);
    if (!report(sources, program)) {
        return 1;
    }
    if (command == "asm") {
        return assemble_command(program);
    }
    if (command == "header") {
        std::vector<std::string> files;
        for (const Sources::Part &part : sources.parts) {
            files.push_back(part.path);
        }
        return header_command(program, files);
    }
    if (command != "sim") {
        return usage();
    }

    int passes = 4;
    std::vector<std::string> watch;
    std::vector<ScriptedWrite> writes;
    for (; arg < argc; ++arg) {
        const std::string option = argv[arg];
        if (arg + 1 >= argc) {
            return usage();
        }
        const std::string value = argv[++arg];
        if (option == "-n") {
            passes = std::atoi(value.c_str());
        } else if (option == "-w") {
            if (!program.symbols.contains(value)) {
                std::fprintf(stderr, "unknown name %s\n", value.c_str());
                return 2;
            }
            watch.push_back(value);
        } else if (option == "-s") {
            const size_t equals = value.find('=');
            const size_t at     = value.find('@');
            if (equals == std::string::npos || at == std::string::npos
                || at < equals) {
                return usage();
            }
            const std::string name = value.substr(0, equals);
            if (!program.symbols.contains(name)) {
                std::fprintf(stderr, "unknown name %s\n", name.c_str());
                return 2;
            }
            writes.push_back(
                    {program.symbols.at(name),
                     std::atoi(
                             value.substr(equals + 1, at - equals - 1).c_str()),
                     std::atoi(value.substr(at + 1).c_str())});
        } else {
            return usage();
        }
    }
    return simulate_command(program, passes, watch, writes);
}
